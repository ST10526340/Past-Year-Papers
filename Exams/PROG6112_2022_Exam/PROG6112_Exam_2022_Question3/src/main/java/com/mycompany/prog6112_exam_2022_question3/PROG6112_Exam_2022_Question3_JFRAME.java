    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:

        String startLocation = (String) cmbStartLocation.getSelectedItem();
        String endLocation = (String) cmbEndLocation.getSelectedItem();

        if (startLocation.equalsIgnoreCase(endLocation)) {
            JOptionPane.showMessageDialog(rootPane, "Destination cannot be the same!!!", "", JOptionPane.INFORMATION_MESSAGE);

        } else {
            String vehicleType = (String) cmbTravelBy.getSelectedItem();

            txtDisplay.setText("TRAVEL LOG\n" + "*".repeat(30) + "\nDestination 1:" + startLocation + "\nDestination 2: "
                    + endLocation + "\nTravel By: " + vehicleType + "\n" + "*".repeat(30)
            );

        }
    }//GEN-LAST:event_btnSubmitActionPerformed

