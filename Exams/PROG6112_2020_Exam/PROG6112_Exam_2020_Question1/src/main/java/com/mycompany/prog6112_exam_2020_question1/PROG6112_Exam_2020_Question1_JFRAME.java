    private void menu_Tools_YearlyUsageActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menu_Tools_YearlyUsageActionPerformed
        // TODO add your handling code here:
        String[] Printers = new String[cmbPrinter.getItemCount()];
        
        for (int i = 0; i < cmbPrinter.getItemCount(); i++) {
            Printers[i] = (String) cmbPrinter.getItemAt(i);
        }
        String line = "";
        
        for (int row = 0; row < ink.length; row++) {
            int inkSum = 0;
            for (int col = 0; col < ink[row].length; col++) {
                inkSum += ink[row][col];
                
            }//for col

            line += "Total cartirage use for " + Printers[row] + " is " + inkSum + "\n";
            
        }//for row
        JOptionPane.showMessageDialog(rootPane, line, "Message", JOptionPane.INFORMATION_MESSAGE);
        //yearly usage

    }//GEN-LAST:event_menu_Tools_YearlyUsageActionPerformed

