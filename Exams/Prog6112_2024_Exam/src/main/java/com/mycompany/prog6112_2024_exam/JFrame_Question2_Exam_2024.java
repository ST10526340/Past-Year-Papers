    private void Menu_Edit_ProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Menu_Edit_ProcessActionPerformed
        // TODO add your handling code here: when proccess clicked perform these actions

        String movie = (String) cmbMoives.getSelectedItem();
        int numTickets = Integer.parseInt(edtNumTickets.getText());
        double ticketPrice = Double.parseDouble(edtTicketPrice.getText());
        double total = (numTickets * ticketPrice) * 1.14;

        MovieTickets chk = new MovieTickets(numTickets, ticketPrice, movie);

        //MovieTicketData data = MovieTicketData.MovieName;
        String content = "MOVIE TICKET REPORT" + "\n" + "*".repeat(40) + "\n" + "MOVIE NAME: " + movie + "\n" + "MOVIE TICKET PRICE: R"
                + ticketPrice + "\n" + "NUMBEROF TICKETS: " + numTickets + "\n" + "TOTAL TICKET PRICE: R" + total + "\n" + "*".repeat(40);

        if (chk.fullCheck() == true) {

            txtArea.setText(content);
            Path filePath = Path.of("C:\\Users\\USER-PC\\Desktop\\UNI\\NetbeanProjects\\Prog6112_2024_Exam\\src\\main\\java\\com\\mycompany\\prog6112_2024_exam\\report.txt");

            try {
                Files.writeString(filePath, content);
                System.out.println("File saved successfully.");
            } catch (IOException e) {
                System.out.println("An error occurred: " + e.getMessage());
            }
        } else {
            txtArea.setText("An invalid input has been entered, please correct it and try again!");
        }//else

    }//GEN-LAST:event_Menu_Edit_ProcessActionPerformed

