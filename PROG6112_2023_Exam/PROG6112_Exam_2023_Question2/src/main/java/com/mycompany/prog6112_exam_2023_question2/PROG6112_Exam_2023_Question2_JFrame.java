    private void menu_Edit_SaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menu_Edit_SaveActionPerformed
        // TODO add your handling code here:
        String AgentLocation = cmbLocations.getSelectedItem().toString();
        String name = edtAgentName.getText();
        double PropertyPrice = Integer.parseInt(edtPrice.getText());
        int commissionPercentage = Integer.parseInt(edtCommission.getText());
        double commission = (PropertyPrice * (commissionPercentage / 100));

        String content = "ESTATE AGENT REPORT\n" + "*".repeat(30) + "\n" + "AGENT LOCATION: " + AgentLocation + "\nAGENT NAME: " + name + "\nPROPERTY PRICE: R"
                + PropertyPrice + "\nCOMMISSION PERCENTAGE: " + commissionPercentage + "% \nCALCULATED COMMISSION: R" + commission + "\n" + "*".repeat(30);
        Path filePath = Path.of("C:\\Users\\USER-PC\\Desktop\\UNI\\NetbeanProjects\\PROG6112_Exam_2023_Question2\\src\\main\\java\\com\\mycompany\\prog6112_exam_2023_question2\\Report.txt");

        try {
            // Creates the file if it doesn't exist, or overwrites it if it does
            Files.writeString(filePath, content);
            System.out.println("File saved successfully!");
        } catch (IOException e) {
            System.out.println("An error occurred: " + e.getMessage());
        }
    }//GEN-LAST:event_menu_Edit_SaveActionPerformed

