    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:  
        String prodID = edtProductId.getText();
        String prodName = edtProductName.getText();
        String prodPrice = edtProductPrice.getText();
        
        display += "ID" + prodID + "\n" + "Name:" + prodName + "\nPrice: " + prodPrice;
        txtDisplay.setText(display);
        
        Path filePath = Path.of("C:\\Users\\USER-PC\\Desktop\\UNI\\NetbeanProjects\\PROG6112_Exam_2020_Question3\\src\\main\\java\\com\\mycompany\\prog6112_exam_2020_question3\\products.txt");
        String content = prodID + "\n" + prodName + "\n" + prodPrice;
        
        try {
            // Overwrites the file if it already exists
            Files.writeString(filePath, content, StandardOpenOption.APPEND);

            // To append text instead, add StandardOpenOption.APPEND:
            // Files.writeString(filePath, "\nMore text", StandardOpenOption.APPEND);
        } catch (IOException e) {
            e.printStackTrace();
        }

    }//GEN-LAST:event_btnSubmitActionPerformed

