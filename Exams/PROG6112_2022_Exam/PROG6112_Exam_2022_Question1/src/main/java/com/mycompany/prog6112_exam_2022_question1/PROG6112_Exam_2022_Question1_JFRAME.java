    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:

        inspectionCount += 1;

        if (inspectionCount > 5) {
            JOptionPane.showMessageDialog(rootPane, "Maximum inspection count reached", "Max inspection count", JOptionPane.INFORMATION_MESSAGE);

        } else {
            HospitalInfo[0] = "Hospital Name: " + edtName.getText() + "\nHospital Location: "
                    + edtLocation.getText() + "\nYears since inspection: " + (String) cmbYears.getSelectedItem() + "\n" + "*".repeat(40);
        }


    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnPrintActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrintActionPerformed
        // TODO add your handling code here:
        if (inspectionCount <= 5) {
            txtDisplay.setText(HospitalInfo[0]);
        }

    }//GEN-LAST:event_btnPrintActionPerformed

