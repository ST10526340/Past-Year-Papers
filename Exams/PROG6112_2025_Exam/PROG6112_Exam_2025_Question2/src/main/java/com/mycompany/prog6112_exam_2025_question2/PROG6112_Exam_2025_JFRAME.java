    private void btnLoadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadActionPerformed
        // TODO add your handling code here: btn clicked to load data
        int[][] sales = {{300, 150, 700}, {250, 200, 600}};
        int total = 0;
        int count = 0;
        int yearCount = 0;
        for (int row = 0; row < sales.length; row++) {
            yearCount += 1;
            for (int col = 0; col < sales[row].length; col++) {
                total += sales[row][col];
                count += 1;
            }//col

        }//row
        double avg = total / count;
        int overSals = 0;
        int underSales = 0;
        for (int row = 0; row < sales.length; row++) {

            for (int col = 0; col < sales[row].length; col++) {
                if (sales[row][col] < avg) {
                    underSales += 1;

                } else {
                    overSals += 1;
                }//else
            }//col

        }//row

        txtDisplay.setText("DATA LOG" + "\n" + "*".repeat(30) + "\nTotal sales: " + total + "\nAverage Sales: " + avg + "\nSales over limit: "
                + overSals + "\nSales under limit: " + underSales + "\n" + "*".repeat(30));
        lblYear.setText("Years processed: " + yearCount);
    }//GEN-LAST:event_btnLoadActionPerformed

