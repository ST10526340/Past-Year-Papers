    private void menu_Edit_ReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menu_Edit_ReportActionPerformed
        // TODO add your handling code here:

        int[][] lessonCost = {{150, 250, 280}, {215, 232, 280}, {130, 185, 310}};
        double[] costAVG = new double[lessonCost.length];

        for (int row = 0; row < lessonCost.length; row++) {

            int sum = 0;
            int count = 0;
            for (int col = 0; col < lessonCost[row].length; col++) {
                sum += lessonCost[row][col];
                count += 1;

            }//col
            costAVG[row] = sum / count;

        }//row

        String line = "";
        for (int i = 0; i < costAVG.length; i++) {

            line += "Average lesson price for " + (String) cmbLevel.getItemAt(i) + ": R " + String.format("%.0f", costAVG[i]) + "\n";

        }//for i
        JOptionPane.showMessageDialog(rootPane, line, "Message", JOptionPane.INFORMATION_MESSAGE);


    }//GEN-LAST:event_menu_Edit_ReportActionPerformed

